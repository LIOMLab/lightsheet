"""Golden-master capture harness for the acquire_scan signal sequence.

This module is the SOLE regeneration path for ``test/golden/default.json``
(D-12). The fixture is generated by running::

    uv run python test/golden/_record.py

and is committed to the repo. It must NOT be hand-edited — a hand-edit
would mask the exact regression this safety net exists to catch. The
replay test ``test/test_golden_acquisition.py`` asserts
``capture_acquisition_sequence("default") == json.load(default.json)``;
regenerating the fixture after a refactor produces a diff that is the
behavioral change to review.

Determinism sources (EDGE — flagged-unverified assumption, documented here
so the safety net's integrity is auditable):

* ``MockSigGen`` reuses the pure-numpy ``lightsheet.waveforms`` generators
  with hardcoded synthetic config defaults (sample_rate=40000, etc.) — no
  config.ini read, no hardware, no random seed. The same inputs always
  produce bit-identical waveform arrays.
* ``MockCamera`` returns ``np.zeros((n, ysize, xsize), dtype=uint16)``
  canned frames — deterministic shape and content.
* ``MockMotors`` / ``MockETLs`` / ``MockLaser`` track state in plain
  instance attributes with no I/O.

The harness execs the REAL ``Controller_MainWindow.acquire_scan`` body
(via the ``_load_method`` exec-against-Mock pattern from
``test/test_laser_controls.py``) against a Mock stand-in ``self`` whose
HAL attributes are the six ``Mock*`` classes. This runs the real method
source — the same code that runs on the rig — without needing a Qt event
loop or a display (RESEARCH.md §Standard Stack: no pytest-qt). The
ordered ``sig_message.emit`` / ``sig_progress_update.emit`` call sequence
is captured as a JSON list of ``{"type": ..., "value": ...}`` dicts.

``acquire_scan`` references module-level names (``datetime``, ``logger``,
``np``) from ``lightsheet/gui/controller.py``; the exec namespace is
seeded with them so the body resolves them at call time.
"""

import datetime
import json
import logging
import os
import re
from collections.abc import Callable
from typing import Any
from unittest.mock import Mock

import numpy as np

from lightsheet.hal import (
    DeviceBundle,
    MockCamera,
    MockETLs,
    MockLaser,
    MockMotors,
    MockSigGen,
)
from lightsheet.gui.hardware_manager import HardwareManager

_CONTROLLER_SRC = os.path.join(
    os.path.dirname(__file__), "..", "..", "lightsheet", "gui", "controller.py"
)
_ACQ_SRC = os.path.join(
    os.path.dirname(__file__), "..", "..", "lightsheet", "gui", "acquisition_coordinator.py"
)

# Module-level logger the exec'd body references (controller.py:45).
_logger = logging.getLogger("lightsheet.gui.controller")


def _read_controller_source() -> str:
    with open(_CONTROLLER_SRC, encoding="utf-8") as f:
        return f.read()


def _slice_method(src: str, method_sig: str) -> str:
    """Return the body of a method, from its ``def <sig>:`` line up to the
    next top-level ``def``/``@pyqtSlot`` decorator."""
    m = re.search(r"def " + re.escape(method_sig) + r":", src)
    assert m, f"{method_sig} is missing"
    body = src[m.start() :]
    end = re.search(r"\n    def |\n    @pyqtSlot", body[1:])
    if end:
        body = body[: end.start() + 1]
    return body


def _load_method(method_sig: str, src_path: str = _CONTROLLER_SRC) -> Callable[..., Any]:
    """Extract a method body from the given source file and return a callable.

    Defaults to controller.py; pass ``_ACQ_SRC`` for ``acquire_scan`` (moved
    to ``AcquisitionCoordinator`` in the god-object split). The exec
    namespace is seeded with the module-level names the body references
    (``datetime``, ``logger``, ``np``) so the function resolves them at
    call time via its ``__globals__``.
    """
    with open(src_path, encoding="utf-8") as f:
        src = f.read()
    body = _slice_method(src, method_sig)
    namespace: dict[str, Any] = {
        "datetime": datetime,
        "logger": _logger,
        "np": np,
    }
    exec(compile(body, src_path, "exec"), namespace)
    func_name = method_sig.split("(")[0].strip()
    return namespace[func_name]


def _build_standin() -> Mock:
    """Build the Mock stand-in ``self`` for acquire_scan.

    acquire_scan now lives on ``AcquisitionCoordinator`` (god-object split).
    The coordinator reads its own ``self.camera`` / ``self.siggen`` /
    ``self.motors`` attributes and shell-owned state via ``self._shell.*``
    (``sig_message``, ``sig_progress_update``, ``ui.*`` widgets, ``_fs``,
    ``buffer`` / ``reconstructed_frame`` / ``buffer_metadata_*``,
    ``reconstruct_frame`` / ``reconstruct_frame_linear_blend``). The
    stand-in mirrors that shape: it IS the coordinator (``self``), with
    ``self._shell`` a Mock exposing the shell-owned attributes acquire_scan
    reads. The siggen's waveforms are pre-computed so ``waveform_cycles`` /
    ``waveform_metadata`` are populated (the real coordinator calls
    ``compute_scan_waveforms`` before ``acquire_scan``).
    """
    camera = MockCamera()
    siggen = MockSigGen(camera)
    siggen.compute_scan_waveforms()

    standin = Mock()
    # Coordinator's own HAL handles.
    standin.camera = camera
    standin.siggen = siggen
    standin.motors = MockMotors()
    # The coordinator holds list[ILaser] (Wave 3 rewrite). acquire_scan does
    # not reference self.lasers, but the stand-in mirrors hardware_init's
    # shape so a future body change that does read laser state is caught.
    standin.lasers = [
        MockLaser(wavelength=555, max_power_mw=300.0, label="Laser 1 (555 nm)"),
        MockLaser(wavelength=640, max_power_mw=150.0, label="Laser 2 (640 nm)"),
    ]
    standin.etls = MockETLs()

    # Shell reference — acquire_scan reads shell-owned state via self._shell.*
    shell = Mock()
    # Signal mocks — emit calls are captured via call_args_list.
    shell.sig_message = Mock()
    shell.sig_progress_update = Mock()
    # UI widgets acquire_scan reads via self._shell.ui.* (the ONE tolerated
    # cross-tier read in AcquisitionCoordinator).
    shell.ui.lineEdit_saveDescription.text.return_value = "sample"
    shell.ui.checkBox_saveStitchBlend.isChecked.return_value = False
    # FrameSaverController enqueue_frame receives the reconstructed frame.
    shell._fs = Mock()
    # Frame-reconstruction helpers stay on the shell — acquire_scan calls
    # self._shell.reconstruct_frame(self._shell.buffer). Plain Mock
    # callables return Mock instances; the enqueue_frame capture is what
    # the golden replay asserts on (the emission sequence), not the frame
    # content.
    standin._shell = shell

    return standin


def _build_preview_standin() -> Mock:
    """Build the Mock stand-in ``self`` for ``preview_mode_worker``.

    ``preview_mode_worker`` lives on ``AcquisitionCoordinator`` and reads
    its own ``self.camera`` attribute plus shell-owned state via
    ``self._shell.*`` (``preview_mode_started``, ``estop_event``,
    ``ui.doubleSpinBox_cameraExposureTime``, ``_fs``,
    ``sig_message``, ``sig_preview_mode_finished``) and laser control via
    ``self._hw`` (the D-05 fold's ``start_lasers``/``stop_lasers`` calls).
    The stand-in IS the coordinator (``self``); ``self._hw`` is a real
    ``HardwareManager`` backed by a ``DeviceBundle`` of Mock devices so
    the D-05 fold's laser start/stop calls exercise the real
    ``HardwareManager.start_lasers``/``stop_lasers`` path (which emits
    ``sig_message`` only on a HAL error — MockLaser does not error, so
    the happy-path fixture is an empty list, proving the fold introduced
    no stray emission on the message channel).

    ``preview_mode_started`` is ``False`` so the while loop is skipped —
    the scenario exercises the arm → start_lasers → stop_lasers → disarm
    path deterministically without entering the frame-grab loop.
    """
    import threading

    camera = MockCamera()
    siggen = MockSigGen(camera)
    motors = MockMotors()
    etls = MockETLs()
    lasers = (
        MockLaser(wavelength=555, max_power_mw=300.0, label="Laser 1 (555 nm)"),
        MockLaser(wavelength=640, max_power_mw=150.0, label="Laser 2 (640 nm)"),
    )
    bundle = DeviceBundle(
        camera=camera, siggen=siggen, motors=motors, etls=etls, lasers=lasers
    )

    shell = Mock()
    shell.ui.doubleSpinBox_cameraExposureTime.value.return_value = 100
    shell.preview_mode_started = False  # skip the frame-grab loop
    shell.estop_event = threading.Event()
    # Auto-laser flags + staged power — start_lasers/stop_lasers read these.
    shell._auto_laser1 = True
    shell._auto_laser2 = True
    shell.laser1_power_pct = 50.0
    shell.laser2_power_pct = 50.0
    shell._fs = Mock()
    shell.sig_message = Mock()
    shell.sig_progress_update = Mock()
    shell.sig_preview_mode_finished = Mock()

    hw = HardwareManager(bundle, shell)

    standin = Mock()
    standin.camera = camera
    standin._hw = hw
    standin._shell = shell
    return standin


def capture_acquisition_sequence(scenario: str) -> list[dict]:
    """Run the real acquire_scan body against a Mock stand-in and return
    the ordered ``sig_message`` / ``sig_progress_update`` emit sequence.

    ``scenario`` selects the fixture:

    * ``"default"`` — the silent happy path (no DAQ error, no camera
      timeout). Emits zero ``sig_message`` / ``sig_progress_update`` calls;
      the fixture is an empty list. This characterizes the contract: a
      successful acquisition is silent on the message channel.
    * ``"siggen_create_scanner_fail"`` — the siggen ``create_scanner``
      failure early-return path. The stand-in's ``create_scanner`` is
      patched to set ``siggen.error = 1`` +
      ``siggen.error_message = "create_scan error"`` (mirroring the real
      ``SigGen.create_scanner`` bare-except branch), so ``acquire_scan``
      hits its ``if self.siggen.error:`` early-return and emits the
      "Scan task creation failed" ``sig_message``. This closes one error
      path: a dropped or re-sequenced emission on the
      create-scanner failure branch is now catchable, not just the happy
      path.
    * ``"preview_auto_laser"`` — the D-05 preview-auto-laser fold. Runs
      ``preview_mode_worker`` (not ``acquire_scan``) against a stand-in
      whose ``self._hw`` is a real ``HardwareManager`` backed by Mock
      devices. The D-05 fold inserted ``self._hw.start_lasers()`` after
      ``camera.arm()`` and ``self._hw.stop_lasers()`` before
      ``camera.disarm()``; on the happy path (MockLaser, no HAL error)
      the ``sig_message`` sequence is empty — the fold introduced no
      stray emission on the message channel. This is the ONE scenario
      expected to differ from a hypothetical pre-split re-recording:
      before the fold, ``preview_mode_worker`` did not call
      ``start_lasers``/``stop_lasers`` at all; now it does, and a future
      change that makes the preview path emit on the happy path (or
      re-sequences the laser calls relative to arm/disarm) is caught
      here.

    The sequence is a list of ``{"type": "sig_message" |
    "sig_progress", "value": <first positional arg>}`` dicts in emission
    order.
    """
    if scenario not in ("default", "siggen_create_scanner_fail", "preview_auto_laser"):
        raise ValueError(f"unknown scenario: {scenario!r}")

    if scenario == "preview_auto_laser":
        standin = _build_preview_standin()
        worker = _load_method("preview_mode_worker(self) -> None", src_path=_ACQ_SRC)
        worker(standin)
        sequence: list[dict] = []
        for call in standin._shell.sig_message.emit.call_args_list:
            sequence.append({"type": "sig_message", "value": call.args[0]})
        for call in standin._shell.sig_progress_update.emit.call_args_list:
            sequence.append({"type": "sig_progress", "value": call.args[0]})
        return sequence

    standin = _build_standin()
    if scenario == "siggen_create_scanner_fail":
        # Mirror the real SigGen.create_scanner bare-except branch: it sets
        # error=1 + a generic 'create_scan error' message and never raises.
        # acquire_scan resets self.siggen.error = 0 before the call, then
        # checks it after — so the failure must be set inside create_scanner.
        def _fail_create_scanner() -> None:
            standin.siggen.error = 1
            standin.siggen.error_message = "create_scan error"

        standin.siggen.create_scanner = _fail_create_scanner
    acquire_scan = _load_method("acquire_scan(self) -> None", src_path=_ACQ_SRC)
    acquire_scan(standin)

    sequence = []
    for call in standin._shell.sig_message.emit.call_args_list:
        sequence.append({"type": "sig_message", "value": call.args[0]})
    for call in standin._shell.sig_progress_update.emit.call_args_list:
        sequence.append({"type": "sig_progress", "value": call.args[0]})
    return sequence


def record_acquisition(out_path: str, scenario: str = "default") -> None:
    """Capture a scenario and write it to ``out_path`` as JSON."""
    seq = capture_acquisition_sequence(scenario)
    with open(out_path, "w", encoding="utf-8") as f:
        json.dump(seq, f, indent=2)
        f.write("\n")


if __name__ == "__main__":
    base = os.path.dirname(__file__)
    scenarios = {
        "default": os.path.join(base, "default.json"),
        "siggen_create_scanner_fail": os.path.join(
            base, "siggen_create_scanner_fail.json"
        ),
        "preview_auto_laser": os.path.join(base, "preview_auto_laser.json"),
    }
    for name, path in scenarios.items():
        record_acquisition(path, name)
        print(f"Wrote {path}")
